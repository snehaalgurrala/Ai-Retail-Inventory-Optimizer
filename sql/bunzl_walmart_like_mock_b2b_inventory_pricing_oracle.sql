CREATE OR REPLACE VIEW BZ_MOCK_AI_ORDER_DETAIL_VW AS
SELECT
    oh.ORDER_ID,
    oh.ORDER_NBR,
    oh.ORDER_DATE,
    oh.ORDER_CHANNEL,
    oh.ORDER_STATUS,
    oh.PAYMENT_METHOD,
    oh.ORDER_TOTAL_AMT,

    c.CUSTOMER_ID,
    c.CUSTOMER_NBR,
    c.CUSTOMER_NAME,
    c.INDUSTRY,
    c.CUSTOMER_SEGMENT,
    c.CONTRACT_TIER,

    b.BRANCH_ID,
    b.BRANCH_NBR,
    b.BRANCH_NAME,
    b.CITY AS BRANCH_CITY,
    b.STATE AS BRANCH_STATE,

    ol.ORDER_LINE_ID,
    p.PRODUCT_ID,
    p.SKU,
    p.PRODUCT_NAME,
    p.BRAND_NAME,
    p.CATEGORY,
    p.SUB_CATEGORY,

    ol.QUANTITY,
    ol.UNIT_SELLING_PRICE,
    ol.UNIT_COST_PRICE,
    ol.DISCOUNT_AMT,
    ol.LINE_TOTAL_AMT,

    ROUND((ol.UNIT_SELLING_PRICE - ol.UNIT_COST_PRICE), 2) AS UNIT_MARGIN_AMT,
    ROUND(
        CASE
            WHEN ol.UNIT_SELLING_PRICE = 0 THEN 0
            ELSE ((ol.UNIT_SELLING_PRICE - ol.UNIT_COST_PRICE) / ol.UNIT_SELLING_PRICE) * 100
        END, 2
    ) AS UNIT_MARGIN_PCT,

    CASE
        WHEN ol.QUANTITY >= 100 THEN 'ABNORMAL_BULK_QTY'
        WHEN oh.ORDER_TOTAL_AMT >= 5000 THEN 'ABNORMAL_HIGH_VALUE'
        WHEN ol.DISCOUNT_AMT > ol.LINE_TOTAL_AMT * 0.20 THEN 'ABNORMAL_HIGH_DISCOUNT'
        ELSE 'NORMAL'
    END AS AI_ORDER_RISK_SIGNAL

FROM BZ_MOCK_ORDER_HEADER oh
JOIN BZ_MOCK_CUSTOMER c
    ON c.CUSTOMER_ID = oh.CUSTOMER_ID
JOIN BZ_MOCK_BRANCH b
    ON b.BRANCH_ID = oh.BRANCH_ID
JOIN BZ_MOCK_ORDER_LINE ol
    ON ol.ORDER_ID = oh.ORDER_ID
JOIN BZ_MOCK_PRODUCT p
    ON p.PRODUCT_ID = ol.PRODUCT_ID;


/* ============================================================================
   AI-FRIENDLY PRICING INTELLIGENCE VIEW
   ============================================================================ */

CREATE OR REPLACE VIEW BZ_MOCK_AI_PRICING_INTEL_VW AS
SELECT
    b.BRANCH_ID,
    b.BRANCH_NBR,
    b.BRANCH_NAME,
    b.CITY,
    b.STATE,

    p.PRODUCT_ID,
    p.SKU,
    p.PRODUCT_NAME,
    p.BRAND_NAME,
    p.CATEGORY,
    p.SUB_CATEGORY,
    p.COST_PRICE,
    p.CURRENT_SELLING_PRICE,

    i.ON_HAND_QTY,
    i.RESERVED_QTY,
    i.AVAILABLE_QTY,
    i.REORDER_POINT,
    i.SAFETY_STOCK,
    i.REORDER_QTY,
    i.INVENTORY_STATUS,

    ph.REGULAR_PRICE,
    ph.SELLING_PRICE,
    ph.PRICE_TYPE,
    ph.PROMO_DESC,
    ph.EFFECTIVE_DATE,
    ph.EXPIRATION_DATE,

    ROUND((ph.SELLING_PRICE - ph.COST_PRICE), 2) AS UNIT_MARGIN_AMT,
    ROUND(
        CASE
            WHEN ph.SELLING_PRICE = 0 THEN 0
            ELSE ((ph.SELLING_PRICE - ph.COST_PRICE) / ph.SELLING_PRICE) * 100
        END, 2
    ) AS MARGIN_PCT,

    cp.COMPETITOR_NAME,
    cp.COMPETITOR_PRICE,
    ROUND((ph.SELLING_PRICE - cp.COMPETITOR_PRICE), 2) AS PRICE_GAP_VS_COMPETITOR,

    CASE
        WHEN i.AVAILABLE_QTY = 0 THEN 'STOCKOUT_RISK'
        WHEN i.AVAILABLE_QTY <= i.REORDER_POINT THEN 'LOW_STOCK_RISK'
        WHEN i.AVAILABLE_QTY > i.REORDER_POINT * 4 THEN 'OVERSTOCK_RISK'
        ELSE 'NORMAL_STOCK'
    END AS AI_INVENTORY_SIGNAL,

    CASE
        WHEN cp.COMPETITOR_PRICE IS NOT NULL
             AND ph.SELLING_PRICE > cp.COMPETITOR_PRICE * 1.10
             THEN 'PRICE_TOO_HIGH_VS_COMPETITOR'
        WHEN cp.COMPETITOR_PRICE IS NOT NULL
             AND ph.SELLING_PRICE < cp.COMPETITOR_PRICE * 0.90
             THEN 'PRICE_TOO_LOW_VS_COMPETITOR'
        WHEN ((ph.SELLING_PRICE - ph.COST_PRICE) / ph.SELLING_PRICE) < 0.20
             THEN 'LOW_MARGIN_RISK'
        ELSE 'PRICE_ALIGNED'
    END AS AI_PRICE_SIGNAL,

    CASE
        WHEN i.AVAILABLE_QTY = 0 THEN 'REORDER_IMMEDIATELY'
        WHEN i.AVAILABLE_QTY <= i.REORDER_POINT THEN 'REORDER_SOON'
        WHEN cp.COMPETITOR_PRICE IS NOT NULL
             AND ph.SELLING_PRICE > cp.COMPETITOR_PRICE * 1.10
             AND i.AVAILABLE_QTY > i.REORDER_POINT
             THEN 'CONSIDER_PRICE_REDUCTION'
        WHEN cp.COMPETITOR_PRICE IS NOT NULL
             AND ph.SELLING_PRICE < cp.COMPETITOR_PRICE * 0.90
             AND ((ph.SELLING_PRICE - ph.COST_PRICE) / ph.SELLING_PRICE) < 0.25
             THEN 'REVIEW_LOW_MARGIN_PRICE'
        WHEN i.AVAILABLE_QTY > i.REORDER_POINT * 4
             THEN 'CONSIDER_PROMOTION_TO_REDUCE_OVERSTOCK'
        ELSE 'NO_ACTION'
    END AS AI_RECOMMENDED_ACTION

FROM BZ_MOCK_INVENTORY i
JOIN BZ_MOCK_BRANCH b
    ON b.BRANCH_ID = i.BRANCH_ID
JOIN BZ_MOCK_PRODUCT p
    ON p.PRODUCT_ID = i.PRODUCT_ID
JOIN BZ_MOCK_PRICE_HISTORY ph
    ON ph.PRODUCT_ID = i.PRODUCT_ID
   AND ph.BRANCH_ID = i.BRANCH_ID
LEFT JOIN BZ_MOCK_COMPETITOR_PRICE cp
    ON cp.PRODUCT_ID = p.PRODUCT_ID
WHERE ph.EFFECTIVE_DATE <= SYSDATE
  AND NVL(ph.EXPIRATION_DATE, DATE '2999-12-31') >= SYSDATE;

COMMIT;
